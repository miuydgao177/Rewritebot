export function buildRewritePrompt(notes, options) {
  return `
请严格按照“成稿类型、故事主角设定、文风要求、二创方向”生成完成稿。不要使用固定模板，不要写成意识流种草文，也不要写成内容分析报告。

选题：${options.topic}
目标人群：${options.audience}
创作语气：${options.tone}
成稿类型：${formatContentMode(options.contentMode)}
故事主角设定：${options.storyBrief || "按二创方向自行设定一个清晰的人物"}
文风要求：${options.styleGuide || "口语化、自然、有具体画面，不要像总结报告"}
二创方向：${options.angle}

已选真实小红书素材（只作为灵感池和细节池，不要逐条概括，不要复述原文结构）：
${notes.map(formatNoteForPrompt).join("\n\n")}

输出要求：
1. 必须按下面三个分隔符输出，不要输出 JSON，不要输出 Markdown 代码块。
2. 除了三个分隔段之外，不要输出任何解释、分析、前言、备注、过程说明或安全标签。
3. ARTICLE 下必须是一篇可直接发布的小红书图文完成稿。第一行用 h3 写标题，后面直接进入正文，不要写“标题：”“选题判断：”“素材分析：”“创作思路：”。
4. 如果成稿类型是“新故事创作”，ARTICLE 必须生成一个新的完整故事：一个主角、一条时间线、一个关键转折、一个结尾感受。不要把多篇素材排列成“有人说、另一个人说、还有人说”的总结。
5. 故事可以借用素材里的主题、场景、情绪和生活细节，但不要照搬原作者经历，不要写成已选文章内容回顾。
6. ARTICLE 正文必须有开头钩子、4-7 个自然段、结尾互动。读起来要像一个人在讲自己的故事或讲身边人的故事，不像写给运营看的说明。
7. 每一段都要推进故事：开头提出人物处境，中间写具体场景和变化，结尾落到这个人为什么选择留下或改变看法。
8. VIDEO 下生成可直接拍摄的短视频脚本，必须包含分镜时间、画面、口播、字幕和互动收口。
9. BRIEF 下生成运营简报，说明借用了哪些素材共性、故事主线、文风注意点、内容风险、发布建议。
10. 所有正文使用 HTML 片段，只允许 h3、p、ol、ul、li、strong 标签。
11. ARTICLE 禁止出现这些后台词：选题判断、素材、这组内容、这组标题、可以看出、我们可以打造、结合这些信息、读者、用户正在、本文、案例拆解。
12. 不要说“我亲测”“用了两周”“地铁偶遇”“朋友送我”“12小时保温”“500ml”“95%车载架”等任何未在素材或故事设定中明确允许的细节。
13. 不要输出英文夹杂表达，不要使用 REAK、worth、cocoon 这类生硬词。
14. 语义要连贯：每句话必须服务于同一个故事，不要从一个场景突然跳到另一个场景。
15. 如果素材信息不足，可以补充合理的日常桥段，但必须贴近日常生活，不要编造政策、身份文件、真实人物、具体年份、具体城市、金额、数据。
16. 不要使用 emoji，不要使用 Markdown 加粗符号，不要输出话题标签堆叠。
17. 标题不要夸大承诺，不要写“拯救”“神器”“必入”等绝对化表达。
18. 只使用普通人日常能理解的常用词。禁止自造简称、行业黑话、冷门概念和没有必要的抽象词。
19. 禁止使用“国感”“松弛感”“氛围感”“情绪价值”等泛化表达，除非用户明确要求使用；请改成具体描述，例如“外国人对中国生活的真实感受”“让人觉得舒服”“现场给人的感觉”“让人感到被理解”。

===ARTICLE===
这里写文章二创
===VIDEO===
这里写视频脚本
===BRIEF===
这里写运营简报
`;
}

function formatContentMode(value) {
  if (value === "story") return "新故事创作";
  if (value === "guide") return "攻略/清单整理";
  return "文章结构重写";
}

function formatNoteForPrompt(note, index) {
  return [
    `素材 ${index + 1}`,
    `标题：${note.title}`,
    `作者：${note.creator}`,
    `点赞：${note.likes}`,
    `收藏：${note.saves}`,
    `可见摘要：${note.summary}`,
    `可见标题钩子：${note.hook}`,
    `标签：${note.tags?.join("、") || ""}`,
    `来源：${note.sourceUrl || ""}`,
  ].join("\n");
}
